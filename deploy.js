async function exportDeployment() {
  /* The application is split across several source files that sit beside
     index.html on the server. This re-reads each one of those files (not
     the live, rendered DOM) so the package matches what is actually on
     disk, then adds the generated service worker, manifest, icon and a
     README. fetch() cannot read sibling files under file:, so packaging
     only works once the application is already being served over http or
     https — which is also a requirement for the service worker itself. */
  if (location.protocol !== "http:" && location.protocol !== "https:") {
    toast("This only works when the application is opened from a web address rather than from a file on disk. Ask whoever installed it to place the files on the bank's internal server, then try again from there.", "err");
    return;
  }
  try {
    toast("Packaging deployment files...");
    const files = [];
    for (const name of SOURCE_FILES) {
      const res = await fetch(name, { cache: "no-store" });
      if (!res.ok) throw new Error("could not read " + name + " (HTTP " + res.status + ")");
      files.push({ name, data: await res.text() });
    }
    files.push({ name: "rbcci-lpm-sw.js", data: SW_SOURCE });
    files.push({ name: "manifest.webmanifest", data: MANIFEST_SOURCE });
    files.push({ name: "icon.svg", data: ICON_SOURCE });
    files.push({ name: "README.txt", data: DEPLOY_README });
    const blob = await ZipWrite.build(files);
    download("RBCCI_LPMRS_deployment_" + today().replace(/-/g, "") + ".zip", blob);
    audit("Exported deployment package", SOURCE_FILES.length + " source files, service worker, manifest, icon");
    toast("Deployment package exported. Unzip the files into one folder and serve them together.");
  } catch (e) { toast("Packaging failed: " + e.message + ". Each source file must be reachable at its own URL next to index.html.", "err"); }
}

(function registerSw() {
  if (!("serviceWorker" in navigator)) return;
  if (location.protocol !== "http:" && location.protocol !== "https:") return;
  navigator.serviceWorker.register("rbcci-lpm-sw.js")
    .then(function () { audit("Service worker registered", "offline shell active"); })
    .catch(function () { /* not deployed yet; the application still runs */ });
})();
