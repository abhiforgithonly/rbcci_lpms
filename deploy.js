/* --------------------------------------------------- deployment packaging */
/* The application now ships as several source files rather than one HTML
   file. Anything the shell needs to boot while offline — the markup, the
   stylesheet and every script — has to be named here so the install step
   actually caches it; a stale list would silently break offline reloads. */
const SOURCE_FILES = ["index.html", "styles.css", "core.js", "shared/schema.js", "rules.js",
  "engine.js", "afrd.js", "import.js", "views.js", "events.js", "pdf.js", "letters.js", "deploy.js"];

const SW_SOURCE = '/* RBCCI LPMRS service worker, generated by the application.\n'
+ '   Deploy beside index.html and serve both over https or http://localhost. */\n'
+ 'const CACHE = "rbcci-lpmrs-v' + APP.version + '";\n'
+ 'const SHELL = ["./", ' + SOURCE_FILES.map(f => '"./' + f + '"').join(", ") + ', "./manifest.webmanifest", "./icon.svg"];\n'
+ 'self.addEventListener("install", e => {\n'
+ '  e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));\n'
+ '});\n'
+ 'self.addEventListener("activate", e => {\n'
+ '  e.waitUntil(caches.keys()\n'
+ '    .then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k))))\n'
+ '    .then(() => self.clients.claim()));\n'
+ '});\n'
+ 'self.addEventListener("fetch", e => {\n'
+ '  const url = new URL(e.request.url);\n'
+ '  if (url.origin !== self.location.origin) return;   // same-origin only\n'
+ '  if (e.request.method !== "GET") return;\n'
+ '  e.respondWith(caches.match(e.request).then(hit => hit || fetch(e.request).then(res => {\n'
+ '    const copy = res.clone();\n'
+ '    caches.open(CACHE).then(c => c.put(e.request, copy)).catch(() => {});\n'
+ '    return res;\n'
+ '  }).catch(() => caches.match("./index.html"))));\n'
+ '});\n';

